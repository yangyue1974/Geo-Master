/**
 * 固定写进每一份报告的诚实边界。
 *
 * spec §C 给了三条。第四条是补的:B1–B4 一次全上,这是单臂试验,
 * 30 天窗口内没有分批上线的余地,所以任何上升都无法归因到具体修复项。
 * 不写这条,报告读起来会像是证明了"JSON-LD 有用",而它证明不了。
 *
 * 第五条是尺子本身的边界 —— 引擎在实验期内会自己变。
 */
export const HONEST_BOUNDS: string[] = [
  '1. **API 答案是客户端答案的近似。** 绝对值仅供参考,只有**变化量**才是结论依据。' +
    'ChatGPT / Perplexity 的网页端与 API 端走的不是同一条检索链路,引用行为存在系统性差异。',

  '2. **control 档预期不动。** 它是对照组,不是失败项。' +
    '任何实体的「他是谁」类问题都会被维基百科的引用垄断赢走,这在开跑前就已知。' +
    'control 档的真正用途见第 4 节:检测引擎自身的漂移。',

  '3. **被引用 ≠ 获得流量。** 本实验验证的是「让实体进入 AI 答案」这台机器本身转不转,' +
    '不验证它带来多少访问。这两件事需要分开测,不要混着讲。',

  '4. **本实验是单臂的,不能归因到具体修复项。** B1(JSON-LD)/ B2(llms.txt)/ B3(内容资产)/ B4(索引推送)' +
    '在 Day 0 一次性全部上线。若引用率上升,无法区分是哪一项起作用,也无法排除站点自然增长。' +
    '要做归因需要分批上线并延长观察窗口,那是 v1 的事。',

  '5. **尺子在实验期内会自己漂移。** 引擎会更新模型版本与检索索引,OpenRouter 的透传形态也会变。' +
    '每轮复测前必须重跑 `geo verify`,并核对 control 档对手结构;两者任一发生显著变化时,' +
    '本轮结果只能作为观察记录,不能作为结论。',
];

/**
 * 只跑了一台引擎时追加的边界。
 *
 * 由代码判断并写入,不靠人记着 —— 一份没有这条声明的单引擎报告,
 * 读起来和多引擎报告没有区别,而结论的适用范围差了一个量级。
 */
export function boundsFor(engineIds: string[]): string[] {
  const out = [...HONEST_BOUNDS];
  if (engineIds.length === 1) {
    out.push(
      `6. **本轮只测了一台引擎(\`${engineIds[0]}\`),结论不能外推到其他引擎。** ` +
        `不同引擎的检索栈与索引来源不同,对手格局可能完全不同 —— ` +
        `Perplexity 侧被票务平台占据,不代表 ChatGPT 或 Gemini 侧也如此。` +
        `第二引擎未能接入的原因:OpenRouter 上的 OpenAI 检索型号已下架(实测 404),` +
        `普通 chat 型号无原生检索(实测引用全部来自正文,是凭记忆作答),` +
        `Gemini 免费层在本账号所在区域不开放(实测 quota limit: 0)。`,
    );
  }
  return out;
}
